"""Scripted demo mode - explore Nexus with no API keys and no local models.

``nexus task 'anything' --demo`` (or ``nexus serve --demo`` for the sidebar /
panel) runs a deterministic offline script that produces the same event stream a
real run would: routing, tool calls, an approval prompt, a file write, a memory
note and a summary. Nothing is invented about your repo - the script reads real
files and writes into ``demo/``.

Why it exists:
1. you can evaluate the UX before spending a token,
2. CI can exercise the whole loop end to end without secrets,
3. the VS Code sidebar has something to talk to on a fresh checkout.
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any, Sequence

from .config import NexusConfig
from .providers import ProviderRegistry
from .router import RouteDecision, Router
from .types import (
    Completion,
    Event,
    EventType,
    Message,
    Provider,
    TextBlock,
    ToolSpec,
    Usage,
)

DEMO_NOTE_PATH = "demo/nexus-demo-notes.md"


def script_for(task: str, role: str, agent: str, workspace: Path) -> list[tuple[str, dict[str, Any]]]:
    """The demo tool script: read the repo, write a note, remember, verify, finish."""
    readme = workspace / "README.md"
    if readme.is_file():
        target = readme
    else:
        target = next(
            (p for p in sorted(workspace.rglob("*.py")) if ".venv" not in str(p) and p.is_file()),
            readme,
        )
    rel_target = target.relative_to(workspace).as_posix() if target.exists() else "README.md"
    note = (
        "# Nexus demo output\n\n"
        f"- task  : {task}\n"
        f"- role  : {role}\n"
        f"- agent : {agent}\n"
        f"- when  : {time.strftime('%Y-%m-%d %H:%M')}\n\n"
        "Generated by `nexus --demo` (scripted, offline). No model was called.\n"
    )
    return [
        ("read", {"path": rel_target}),
        ("write", {"path": DEMO_NOTE_PATH, "content": note}),
        ("remember", {"text": f"demo run for task: {task[:80]}" if task else "demo run"}),
        ("command", {"command": "echo 'demo mode: no real build or test was executed'"}),
        ("ask", {"role": "qa", "question": f"What should be tested for: {task[:120]}"}),
        ("finish", {}),
    ]


class DemoRunner:
    """Walks the script through the REAL tools and the REAL approval gate."""

    def __init__(self, config: NexusConfig, workspace: Path, emit, gate, guard):
        self.config = config
        self.workspace = Path(workspace)
        self.emit = emit
        self.gate = gate
        self.guard = guard

    def run(self, task: str, *, role: str | None = None, read_only: bool = False):
        from .agent import RunResult
        from .tools import READ_ONLY_TOOLS, ToolContext, build_tools

        router = Router(self.config, None)
        decision: RouteDecision = router.route(task, forced=role)
        active_role = decision.role
        agent_cfg = self.config.agent_for_role(active_role)

        self.emit(Event(EventType.ROLE, {
            "role": active_role.name, "agent": agent_cfg.name, "method": decision.method,
            "score": decision.score, "hits": decision.hits, "note": "demo mode (scripted)",
        }))
        self.emit(Event(EventType.AGENT, {
            "agent": agent_cfg.name, "model": agent_cfg.model, "provider": agent_cfg.provider,
            "role": active_role.name, "tool_mode": agent_cfg.tool_mode,
        }))
        self.emit(Event(EventType.STATUS, {
            "message": "DEMO MODE - scripted run: no model called, no tokens spent",
        }))

        ctx = ToolContext(
            workspace=self.workspace,
            guard=self.guard,
            gate=self.gate,
            config=self.config,
            providers=_DemoConsultRegistry(self.config),
            emit=self.emit,
            max_output_chars=self.config.settings.max_output_chars,
            max_read_chars=self.config.settings.max_read_chars,
            command_timeout=self.config.settings.command_timeout,
        )
        registry = build_tools(ctx, role=active_role.name, include_ask_agent=True)
        if active_role.tools:
            registry.keep_only(set(active_role.tools))
        if read_only:
            registry.keep_only(READ_ONLY_TOOLS)

        started = time.time()
        usage = Usage()
        tool_calls = 0
        turns = 0
        last_text = ""

        for kind, payload in script_for(task, active_role.name, agent_cfg.name, self.workspace):
            turns += 1
            if kind == "read":
                name, args = "read_file", {"path": payload["path"], "start_line": 1, "end_line": 12}
                prose = f"Reading `{payload['path']}` before changing anything."
            elif kind == "write":
                name, args = "write_file", payload
                prose = f"Writing `{payload['path']}` so you can see the approval gate and the diff."
            elif kind == "remember":
                name, args = "remember", payload
                prose = f"Saving a note to `{active_role.name}` role memory (Phase 7)."
            elif kind == "command":
                name, args = "run_command", payload
                prose = "Running a harmless verification command."
            elif kind == "ask":
                name = "ask_agent"
                args = {"role": payload["role"], "question": payload["question"]}
                prose = f"Consulting the `{payload['role']}` specialist (Phase 6 primitive)."
            else:
                summary = (
                    f"[demo] routed the task to {active_role.name} ({agent_cfg.name}), inspected the repo "
                    f"and wrote {DEMO_NOTE_PATH}"
                )
                registry.call("finish", {
                    "summary": summary,
                    "followups": [
                        "run the same task without --demo once ANTHROPIC_API_KEY or Ollama is available",
                        "run `nexus doctor` to check every configured agent endpoint",
                    ],
                })
                last_text = summary
                break

            if not registry.has(name):
                self.emit(Event(EventType.STATUS, {"message": f"demo step '{name}' is not available here"}))
                continue
            self.emit(Event(EventType.TEXT, {"text": prose, "role": active_role.name}))
            last_text = prose
            _result, is_error = registry.call(name, args)
            tool_calls += 1
            usage.add(Usage(120, 40, 1))
            if is_error:
                self.emit(Event(EventType.STATUS, {"message": f"demo step '{name}' was denied or failed"}))

        return RunResult(
            text=last_text,
            role=active_role.name,
            agent=agent_cfg.name,
            method=decision.method,
            turns=turns,
            usage=usage,
            tool_calls=tool_calls,
            changed_files=sorted(ctx.state.get("changed_files", set())),
            summary=ctx.state.get("summary", ""),
            followups=ctx.state.get("followups", []),
            stopped_reason="demo script complete",
            duration_s=time.time() - started,
            messages=[Message(role="user", content=task)],
            ok=True,
        )


class _DemoConsultRegistry(ProviderRegistry):
    """Answers `ask_agent` locally so the demo never needs a live model."""

    def __init__(self, config: NexusConfig):
        super().__init__(dict(config.agents))
        self.config = config

    def call_with_fallback(self, name: str, system: str, messages, tools=None, **kwargs):
        question = ""
        for message in messages:
            if isinstance(message.content, str):
                question = message.content
        answer = (
            "[demo answer - no model was called]\n"
            f"Asked: {question.strip().splitlines()[-1][:160]}\n"
            "A real specialist would reply with: the happy path, the validation errors, "
            "and one integration case to cover."
        )
        return _DemoProvider(name), Completion(
            content=[TextBlock(text=answer)], stop_reason="end_turn", model="demo"
        )


class _DemoProvider(Provider):
    kind = "demo"

    def __init__(self, name: str):
        self.name = name
        self.model = "demo"

    def complete(self, system, messages, tools=None, **kwargs) -> Completion:
        return Completion(content=[TextBlock(text="[demo]")], stop_reason="end_turn", model="demo")

    def health(self) -> tuple[bool, str]:
        return True, "demo provider (scripted, offline)"


def patch_agent_for_demo(agent) -> None:
    """Swap a real :class:`NexusAgent`'s run loop for the scripted demo."""
    runner = DemoRunner(agent.config, agent.ws, agent.emit, agent.gate, agent.guard)

    def run(task: str, *, role: str | None = None, read_only: bool = False,
            max_turns: int | None = None, history: Sequence[Message] | None = None,
            extra_system: str = ""):
        result = runner.run(task, role=role, read_only=read_only)
        agent.active_role = agent.config.role(result.role)
        agent.sticky_role = result.role
        return result

    def chat_turn(text: str, *, role: str | None = None, read_only: bool = False):
        result = run(text, role=role, read_only=read_only)
        agent.history.extend([
            Message(role="user", content=text),
            Message(role="assistant", content=result.text),
        ])
        return result

    def run_pipeline(name: str, task: str, **kwargs):
        pipeline = agent.config.pipeline(name)
        if pipeline is None:
            known = ", ".join(sorted(agent.config.pipelines)) or "none"
            raise KeyError(f"unknown pipeline '{name}' (defined: {known})")
        results = []
        handoff = ""
        for index, step in enumerate(pipeline.steps, 1):
            step_task = f"{task}\n\n[step {index}/{len(pipeline.steps)}: {step.get('instruction', '')}]"
            if handoff:
                step_task += f"\n\n[handoff from the previous specialist]\n{handoff}"
            result = run(step_task, role=str(step.get("role") or "general"),
                         read_only=bool(step.get("read_only", False)))
            results.append(result)
            handoff = result.summary or result.text
        return results

    agent.run = run                    # type: ignore[method-assign]
    agent.chat_turn = chat_turn        # type: ignore[method-assign]
    agent.run_pipeline = run_pipeline  # type: ignore[method-assign]
    agent.demo_mode = True             # type: ignore[attr-defined]
